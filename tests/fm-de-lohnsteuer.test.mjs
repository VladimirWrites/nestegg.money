const lst = (year, inputs) => {
  const l = new PAP[year](inputs).calc();
  return l.LSTLZZ.divide(new BigDecimal(100)).doubleValue();
};

for (const [year, { kvz, rows }] of Object.entries(ALLGEMEIN)) {
  test(`Lohnsteuer ${year} matches the official Allgemeine Prüftabelle (${Object.keys(rows).length} gross levels x 6 classes)`, () => {
    for (const [gross, expected] of Object.entries(rows)) {
      for (let stkl = 1; stkl <= 6; stkl++) {
        const got = lst(+year, {
          LZZ: 1, RE4: new BigDecimal(+gross * 100), STKL: stkl,
          KVZ: new BigDecimal(kvz), PVZ: stkl === 2 ? 0 : 1, KRV: 0, PKV: 0,
        });
        assert.equal(got, expected[stkl - 1], `${year} gross ${gross} STKL ${stkl}`);
      }
    }
  });
}

for (const [year, { krv, pkpv, rows }] of Object.entries(BESONDERE)) {
  test(`Lohnsteuer ${year} matches the official Besondere Prüftabelle (private insurance rows)`, () => {
    for (const [gross, expected] of Object.entries(rows)) {
      for (let stkl = 1; stkl <= 6; stkl++) {
        const got = lst(+year, {
          LZZ: 1, RE4: new BigDecimal(+gross * 100), STKL: stkl,
          KVZ: BigDecimal.ZERO, PVZ: 0, KRV: krv, PKV: 1, PKPV: new BigDecimal(pkpv(stkl)),
        });
        assert.equal(got, expected[stkl - 1], `${year} gross ${gross} STKL ${stkl}`);
      }
    }
  });
}
